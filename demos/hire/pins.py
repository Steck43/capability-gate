#!/usr/bin/env python3
"""Fail-when-removed pins: every mutant in mutants.yaml must turn its tests red.

    python demos/hire/pins.py [--only ID ...] [--jobs N] [--out DIR]

For each mutant the tree is copied to a scratch folder (no .git, caches or
outputs), the mutant's ``find`` text is replaced once in its file (the text
must occur exactly once, else the mutant is BROKEN), and its tests run with
pytest. Verdicts:

  KILLED    the unmutated copy passes the tests and the mutant fails them
            (pytest exit 1)
  SURVIVED  the mutant still passes: the control is not load-bearing for
            that claim, or the tests are hollow
  BROKEN    the find text is missing or repeated, the baseline is red, or
            pytest ended with anything but 0 or 1 (collection error, crash)

Writes PIN-LIST.md and pins.json to --out. Exit 0 only when every mutant is
KILLED. The working tree is never edited.
"""

from __future__ import annotations

import argparse
import concurrent.futures as cf
import json
import os
import shutil
import subprocess
import sys
import tempfile
from dataclasses import asdict, dataclass
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "demos" / "hire" / "mutants.yaml"
IGNORE = shutil.ignore_patterns(
    ".git",
    "__pycache__",
    ".pytest_cache",
    "out",
    ".venv",
    "*.pyc",
    ".hypothesis",
    ".tmp",
)


@dataclass
class PinResult:
    id: str
    claim_id: str
    file: str
    tests: list[str]
    verdict: str
    detail: str


def load(path: Path = REGISTRY) -> list[dict]:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    rows = data["mutants"]
    ids = [r["id"] for r in rows]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate mutant id in registry")
    return rows


def _pytest(tree: Path, tests: list[str]) -> subprocess.CompletedProcess:
    env = dict(os.environ)
    env.pop("FLOOR_RUN_RECORD", None)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    return subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-x", "-p", "no:cacheprovider", *tests],
        cwd=tree,
        capture_output=True,
        text=True,
        env=env,
        timeout=600,
        check=False,
    )


def apply(tree: Path, mutant: dict) -> str | None:
    """Apply one mutant in ``tree``. None on success, else why not."""
    target = tree / mutant["file"]
    if not target.is_file():
        return f"file {mutant['file']} missing"
    text = target.read_text(encoding="utf-8")
    n = text.count(mutant["find"])
    if n != 1:
        return f"find text occurs {n} times in {mutant['file']}"
    target.write_text(
        text.replace(mutant["find"], mutant["replace"], 1), encoding="utf-8"
    )
    return None


def run_one(mutant: dict, src: Path = ROOT) -> PinResult:
    base = PinResult(
        mutant["id"], mutant["claim_id"], mutant["file"], list(mutant["tests"]), "", ""
    )
    with tempfile.TemporaryDirectory(prefix=f"pin-{mutant['id']}-") as tmp:
        tree = Path(tmp) / "tree"
        shutil.copytree(src, tree, ignore=IGNORE, symlinks=True)
        clean = _pytest(tree, mutant["tests"])
        if clean.returncode != 0:
            base.verdict = "BROKEN"
            base.detail = "baseline red: " + clean.stdout.strip().splitlines()[-1:][0]
            return base
        why = apply(tree, mutant)
        if why:
            base.verdict, base.detail = "BROKEN", why
            return base
        proc = _pytest(tree, mutant["tests"])
        last = (proc.stdout.strip().splitlines() or [""])[-1]
        if proc.returncode == 1:
            base.verdict, base.detail = "KILLED", last
        elif proc.returncode == 0:
            base.verdict, base.detail = "SURVIVED", last
        else:
            base.verdict, base.detail = (
                "BROKEN",
                f"pytest exit {proc.returncode}: {last}",
            )
    return base


def render(results: list[PinResult]) -> str:
    out = [
        "# Fail-when-removed pin list",
        "",
        "Each row deletes or flips one control in a scratch copy of the tree and",
        "runs the listed tests. KILLED means the tests went red without the",
        "control and pass with it. Generated by `python demos/hire/pins.py`.",
        "",
        "| Mutant | Claim | File | Tests | Verdict |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        tests = "<br>".join(f"`{t}`" for t in r.tests)
        out.append(f"| {r.id} | {r.claim_id} | `{r.file}` | {tests} | {r.verdict} |")
    killed = sum(r.verdict == "KILLED" for r in results)
    out += ["", f"KILLED {killed} of {len(results)}."]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--only", nargs="*", default=None)
    ap.add_argument("--jobs", type=int, default=min(8, os.cpu_count() or 2))
    ap.add_argument("--out")
    args = ap.parse_args(argv)
    mutants = load()
    if args.only:
        mutants = [m for m in mutants if m["id"] in set(args.only)]
    with cf.ThreadPoolExecutor(max_workers=args.jobs) as pool:
        results = list(pool.map(run_one, mutants))
    for r in results:
        print(f"{r.verdict:<8} {r.id:<22} {r.claim_id:<32} {r.detail}")
    if args.out:
        out = Path(args.out)
        out.mkdir(parents=True, exist_ok=True)
        (out / "PIN-LIST.md").write_text(render(results), encoding="utf-8")
        (out / "pins.json").write_text(
            json.dumps([asdict(r) for r in results], indent=2) + "\n", encoding="utf-8"
        )
    ok = bool(results) and all(r.verdict == "KILLED" for r in results)
    print(f"pins: {sum(r.verdict == 'KILLED' for r in results)}/{len(results)} KILLED")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
